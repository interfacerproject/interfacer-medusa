import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import type { ExecArgs, ICartModuleService, IOrderModuleService, IPaymentModuleService } from "@medusajs/framework/types"
import { Modules } from "@medusajs/framework/utils"
import { completeCartWorkflow } from "@medusajs/medusa/core-flows"
import type InterfacerService from "../modules/interfacer/service"
import { INTERFACER_MODULE } from "../modules/interfacer"
// Deliberately no direct hook import: Medusa's workflow loader must register it.

export default async function verify({ container }: ExecArgs) {
  const state = JSON.parse(await readFile("../.tmp/p2-state.json", "utf8"))
  const orders = container.resolve<IOrderModuleService>(Modules.ORDER)
  const carts = container.resolve<ICartModuleService>(Modules.CART)
  const payments = container.resolve<IPaymentModuleService>(Modules.PAYMENT)
  const integration = container.resolve<InterfacerService>(INTERFACER_MODULE)
  const before = (await orders.listAndCountOrders({}))[1]
  // No HTTP middleware: the workflow hook itself must refuse an unbound customer.
  const { errors } = await completeCartWorkflow(container).run({
    input: { id: state.unbound_cart }, throwOnError: false,
  })
  assert.match(errors[0]?.error.message, /interfacer_bound_customer_required/)
  assert.equal((await orders.listAndCountOrders({}))[1], before)
  assert.equal((await carts.retrieveCart(state.unbound_cart)).completed_at, null)
  const [session] = await payments.listPaymentSessions({ payment_collection_id: state.unbound_collection })
  assert.equal(session.status, "pending")
  assert.equal(session.authorized_at, null)
  // Autogenerated service mutations must not be able to rebind or soft-delete.
  await assert.rejects(() => integration.updateIdentityLinks({
    id: state.identity_id, person_id: "forged",
  }), /interfacer_immutable/)
  await assert.rejects(() => integration.softDeleteIdentityLinks([state.identity_id]), /interfacer_immutable/)
  console.log("PASS direct completeCartWorkflow (fixture mode disabled) refuses UNBOUND; no order, authorization or cart completion; IdentityLink DB update/soft-delete blocked.")
}
